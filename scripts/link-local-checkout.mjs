/**
 * Rewrite pnpm-workspace.yaml's `overrides` block to link the @deepseek-ai
 * packages to a local deepseek-harness checkout (debug-era linkage — the
 * handoff's Prompt 0.3). The committed workspace file carries no overrides,
 * so a fresh clone resolves @deepseek-ai/dsh-* from the npm registry.
 *
 * Usage: node scripts/link-local-checkout.mjs <checkout-root>
 *        or set DEEPSEEK_HARNESS_CHECKOUT.
 *
 * After running: pnpm install
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const checkoutArg = process.argv[2] ?? process.env.DEEPSEEK_HARNESS_CHECKOUT
if (checkoutArg === undefined || checkoutArg.trim() === '') {
  console.error('Usage: pnpm link:checkout -- <deepseek-harness checkout-root>')
  process.exit(1)
}
const checkout = checkoutArg.replace(/\\/g, '/')
if (!existsSync(`${checkout}/pnpm-workspace.yaml`)) {
  console.error(`link-local-checkout: deepseek-harness checkout not found at ${checkout}`)
  process.exit(1)
}

const links = {
  '@deepseek-ai/cordis': 'vendor/cordis',
  '@deepseek-ai/cordis-plugin-loader': 'vendor/loader',
  '@deepseek-ai/dsh-agent': 'packages/core/agent',
  '@deepseek-ai/dsh-api-remotes': 'packages/api/remotes',
  '@deepseek-ai/dsh-client-runtime': 'packages/client/runtime',
  '@deepseek-ai/dsh-client-ui-input-trigger': 'packages/client/ui-input-trigger',
  '@deepseek-ai/dsh-fs': 'packages/fs/fs',
  '@deepseek-ai/dsh-llm': 'packages/llm/llm',
  '@deepseek-ai/dsh-typert-protocol': 'packages/typert/protocol',
}

const block = [
  '# Local-checkout linkage (generated by scripts/link-local-checkout.mjs —',
  '# delete this block to fall back to registry versions).',
  'overrides:',
  ...Object.entries(links).map(([name, rel]) => `  '${name}': 'link:${checkout}/${rel}'`),
]

const ws = new URL('../pnpm-workspace.yaml', import.meta.url)
const text = readFileSync(ws, 'utf8')
const marker = '# Local-checkout linkage'
const head = text.includes(marker) ? text.slice(0, text.indexOf(marker)) : text
writeFileSync(ws, `${head.trimEnd()}\n\n${block.join('\n')}\n`)
console.log(`link-local-checkout: @deepseek-ai packages linked to ${checkout} — run pnpm install`)
